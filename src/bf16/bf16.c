#include "bf16.h"

uint16_t bf16_from_f32(uint32_t f32bits)
{
    if ((f32bits & 0x7F800000) == 0x7F800000)
        return f32bits >> 16;
    return (f32bits + 0x7FFF + ((f32bits >> 16) & 1)) >> 16;
}

uint16_t bf16_mul(uint16_t a, uint16_t b)
{
    uint16_t sign = (a ^ b) & 0x8000;
    uint32_t aa = a & 0x7FFF;
    uint32_t bb = b & 0x7FFF;

    if (aa - 1 >= 0x7F7F || bb - 1 >= 0x7F7F) {
        if (aa >= 0x7F80) { /* a is Inf or NaN */
            if (aa > 0x7F80)
                return a;
            return bb ? (sign | 0x7F80) : 0x7FC0;
        }
        if (bb >= 0x7F80) { /* b is Inf or NaN */
            if (bb > 0x7F80)
                return b;
            return aa ? (sign | 0x7F80) : 0x7FC0;
        }
        return sign;
    }
    int ea = (int) (aa >> 7);
    int eb = (int) (bb >> 7);
    uint32_t ma = a & 0x007F;
    uint32_t mb = b & 0x007F;

    /* Normalize: put the leading one at bit 7.
     * A denormal has the true exponent of e == 1, so start from 1.
     */
    if (ea == 0) {
        ea = 1;
        while (!(ma & 0x80)) {
            ma <<= 1;
            ea--;
        }
    } else {
        ma |= 0x80;
    }
    if (eb == 0) {
        eb = 1;
        while (!(mb & 0x80)) {
            mb <<= 1;
            eb--;
        }
    } else {
        mb |= 0x80;
    }

    /* 8-bit by 8-bit product lies in [2^14, 2^16). */
    uint32_t p = ma * mb;
    int exp = ea + eb - 127;

    /* Renormalize and truncate back to 8 bits with the leading one. */
    if (p & 0x8000) {
        p >>= 8;
        exp++;
    } else {
        p >>= 7;
    }

    if (exp >= 0xFF)
        return sign | 0x7F80; /* overflow to Inf */
    if (exp <= 0) {
        if (exp < -6)
            return sign; /* underflow to zero */
        return sign | (uint16_t) ((p & 0x7F) >> (1 - exp)); /* denormal */
    }
    return sign | (uint16_t) (exp << 7) | (uint16_t) (p & 0x7F);
}

