uint16_t bf16_sqrt(uint16_t a)
{
    uint32_t e = (a >> 7) & 0xFF;

    if (e == 0xFF && (a & 0x7F))
        return a;
    if ((a & 0x7FFF) == 0)
        return 0x0000;
    if (a & 0x8000)
        return 0x7FC0;
    if (e == 0xFF)
        return a;
    if (e == 0)
        return 0x0000;

    /* e is in [1, 254], so (e + 127) >> 1 is in [64, 190]: the result
     * never overflows to Inf or underflows to zero.
     */
    return (uint16_t) ((((e + 127) >> 1) << 7) | sqrt_tab[a & 0xFF]);
}
